using System.Data;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Dapper;
using Microsoft.Data.SqlClient;

namespace NuanSystem.Application.Tests.Infrastructure.Phase7Sql;

// Read-only metadata query. Does not open/close connections, resolve secrets, provision, or enable gates.
internal static class Phase7SqlDestinationSqlReader
{
    internal static string Fingerprint(string text) => Convert.ToHexString(SHA256.HashData(Encoding.Unicode.GetBytes(text)));

    public static async Task<Phase7SqlDestinationObservation> ReadAsync(IDbConnection connection,
        IDbTransaction? transaction, int timeoutSeconds, CancellationToken token)=>
        await ReadWithEvidenceAsync(connection,transaction,timeoutSeconds,token,null);

    internal static async Task<Phase7SqlDestinationObservation> ReadWithEvidenceAsync(IDbConnection connection,
        IDbTransaction? transaction,int timeoutSeconds,CancellationToken token,
        Action<Phase7SqlDestinationObservation,string,IReadOnlyDictionary<string,string>>? capture)
    {
        if (connection is not SqlConnection || connection.State != ConnectionState.Open)
            throw new Phase7SqlGuardException("PHASE7_SQL_PREFLIGHT_PROVIDER");
        var row = await connection.QuerySingleAsync<Row>(new CommandDefinition(Query, transaction: transaction,
            commandTimeout: timeoutSeconds, cancellationToken: token));
        var procedures = JsonSerializer.Deserialize<Procedure[]>(row.Procedures) ?? throw new InvalidOperationException();
        // Encrypted/invisible definitions cannot be hashed as an empty, apparently valid module.
        if (procedures.Any(p => p.Definition is null)) throw new InvalidOperationException();
        var definitions=procedures.ToDictionary(p=>p.Name,p=>p.Definition!,StringComparer.Ordinal);
        var observation=new Phase7SqlDestinationObservation(row.ServerName, row.ProductVersion, row.DatabaseName, row.DatabaseId, row.CompanyId,
            row.RunMarker, row.Purpose, row.CompatibilityLevel, row.Collation, row.ReadCommittedSnapshot,
            row.DatabasePrincipal, row.Login, row.OriginalLogin, row.Privileged, row.CanViewDefinition,
            Permissions(row.DatabasePermissions), Permissions(row.ServerPermissions), Permissions(row.ObjectPermissions),
            Fingerprint(row.SchemaInventory), procedures.ToDictionary(p => p.Name, p => Fingerprint(p.Definition!), StringComparer.Ordinal),
            row.Spid, row.TransactionCount, row.TransactionState, row.HasFaultMarkers);
        capture?.Invoke(observation,row.SchemaInventory,definitions);
        return observation;
    }

    private static string[] Permissions(string json) => (JsonSerializer.Deserialize<Permission[]>(json)
        ?? throw new InvalidOperationException()).Select(p => p.permission_name).ToArray();
    private sealed record Procedure(string Name, string? Definition);
    private sealed record Permission(string permission_name);
    private sealed class Row
    {
        public string ServerName { get; set; } = "";
        public string ProductVersion { get; set; } = "";
        public string DatabaseName { get; set; } = "";
        public int DatabaseId { get; set; }
        public int CompanyId { get; set; }
        public Guid RunMarker { get; set; }
        public string Purpose { get; set; } = "";
        public int CompatibilityLevel { get; set; }
        public string Collation { get; set; } = "";
        public bool ReadCommittedSnapshot { get; set; }
        public string DatabasePrincipal { get; set; } = "";
        public string Login { get; set; } = "";
        public string OriginalLogin { get; set; } = "";
        public bool Privileged { get; set; }
        public bool CanViewDefinition { get; set; }
        public string DatabasePermissions { get; set; } = "";
        public string ServerPermissions { get; set; } = "";
        public string ObjectPermissions { get; set; } = "";
        public string SchemaInventory { get; set; } = "";
        public string Procedures { get; set; } = "";
        public int Spid { get; set; }
        public int TransactionCount { get; set; }
        public int TransactionState { get; set; }
        public bool HasFaultMarkers { get; set; }
    }

    // Fingerprint protocol v1: exact UTF-16LE SQL JSON, no BOM or newline normalization.
    // The approved schema hash must be generated by this exact query in a separately authorized inventory.
    // SchemaHistory rows are intentionally included: same shape without approved migration history is insufficient.
    internal const string Query = """
        SELECT CONVERT(nvarchar(128),SERVERPROPERTY('ServerName')) ServerName,
          CONVERT(nvarchar(128),SERVERPROPERTY('ProductVersion')) ProductVersion,
          DB_NAME() DatabaseName, DB_ID() DatabaseId,
          (SELECT TRY_CONVERT(int,value) FROM sys.extended_properties WHERE class=0 AND name=N'Phase7.CompanyId') CompanyId,
          (SELECT TRY_CONVERT(uniqueidentifier,CONVERT(nvarchar(128),value)) FROM sys.extended_properties WHERE class=0 AND name=N'Phase7.RunId') RunMarker,
          (SELECT CONVERT(nvarchar(128),value) FROM sys.extended_properties WHERE class=0 AND name=N'Phase7.Purpose') Purpose,
          d.compatibility_level CompatibilityLevel, d.collation_name Collation, d.is_read_committed_snapshot_on ReadCommittedSnapshot,
          USER_NAME() DatabasePrincipal, SUSER_SNAME() Login, ORIGINAL_LOGIN() OriginalLogin,
          CONVERT(bit,CASE WHEN IS_SRVROLEMEMBER('sysadmin')=0 AND USER_NAME() NOT IN ('dbo','guest')
            AND d.state=0 AND d.user_access=0 AND d.is_read_only=0 AND d.source_database_id IS NULL
            AND d.is_trustworthy_on=0 AND d.is_db_chaining_on=0
            AND NOT EXISTS(SELECT 1 FROM sys.user_token u JOIN sys.database_principals p ON p.principal_id=u.principal_id
              WHERE p.type='R' AND p.name<>'public')
            AND NOT EXISTS(SELECT 1 FROM sys.sql_modules WHERE execute_as_principal_id IS NOT NULL)
            AND NOT EXISTS(SELECT 1 FROM sys.crypt_properties)
            AND NOT EXISTS(SELECT 1 FROM sys.assembly_modules)
            AND NOT EXISTS(SELECT 1 FROM sys.synonyms)
            AND NOT EXISTS(SELECT 1 FROM sys.external_tables)
            AND NOT EXISTS(SELECT 1 FROM sys.triggers WHERE parent_class=0)
            THEN 0 ELSE 1 END) Privileged,
          CONVERT(bit,COALESCE(HAS_PERMS_BY_NAME(DB_NAME(),'DATABASE','VIEW DEFINITION'),0)) CanViewDefinition,
          (SELECT permission_name FROM sys.fn_my_permissions(NULL,'DATABASE') ORDER BY permission_name FOR JSON PATH) DatabasePermissions,
          (SELECT permission_name FROM sys.fn_my_permissions(NULL,'SERVER') ORDER BY permission_name FOR JSON PATH) ServerPermissions,
          (SELECT DISTINCT permission_name FROM (
            SELECT p.permission_name FROM sys.objects o
            CROSS APPLY sys.fn_my_permissions(QUOTENAME(SCHEMA_NAME(o.schema_id))+'.'+QUOTENAME(o.name),'OBJECT') p
            WHERE o.is_ms_shipped=0
            UNION ALL SELECT p.permission_name FROM sys.schemas s
              CROSS APPLY sys.fn_my_permissions(QUOTENAME(s.name),'SCHEMA') p
              WHERE s.name NOT IN ('sys','INFORMATION_SCHEMA')
            ) permissions ORDER BY permission_name FOR JSON PATH) ObjectPermissions,
          (SELECT SCHEMA_NAME(p.schema_id)+'.'+p.name Name,m.definition Definition
            FROM sys.procedures p LEFT JOIN sys.sql_modules m ON m.object_id=p.object_id
            WHERE p.is_ms_shipped=0 ORDER BY SCHEMA_NAME(p.schema_id),p.name FOR JSON PATH,INCLUDE_NULL_VALUES) Procedures,
          (SELECT
            JSON_QUERY((SELECT SCHEMA_NAME(o.schema_id) [schema],o.name,o.type,o.principal_id,
              m.definition,m.uses_ansi_nulls,m.uses_quoted_identifier,m.is_schema_bound,m.execute_as_principal_id,
              t.is_disabled,t.is_instead_of_trigger
              FROM sys.objects o LEFT JOIN sys.sql_modules m ON m.object_id=o.object_id
              LEFT JOIN sys.triggers t ON t.object_id=o.object_id WHERE o.is_ms_shipped=0
              ORDER BY SCHEMA_NAME(o.schema_id),o.name FOR JSON PATH,INCLUDE_NULL_VALUES)) objects,
            JSON_QUERY((SELECT SCHEMA_NAME(o.schema_id) [schema],o.name [object],c.name,c.column_id,
              SCHEMA_NAME(ty.schema_id) type_schema,ty.name type_name,
              c.max_length,c.precision,c.scale,c.is_nullable,c.collation_name,c.is_identity,c.is_computed,
              cc.definition computed_definition,dc.definition default_definition,
              CONVERT(nvarchar(128),ic.seed_value) identity_seed,CONVERT(nvarchar(128),ic.increment_value) identity_increment
              FROM sys.columns c JOIN sys.objects o ON o.object_id=c.object_id
              JOIN sys.types ty ON ty.user_type_id=c.user_type_id
              LEFT JOIN sys.computed_columns cc ON cc.object_id=c.object_id AND cc.column_id=c.column_id
              LEFT JOIN sys.default_constraints dc ON dc.object_id=c.default_object_id
              LEFT JOIN sys.identity_columns ic ON ic.object_id=c.object_id AND ic.column_id=c.column_id
              WHERE o.is_ms_shipped=0 ORDER BY SCHEMA_NAME(o.schema_id),o.name,c.column_id FOR JSON PATH,INCLUDE_NULL_VALUES)) columns,
            JSON_QUERY((SELECT SCHEMA_NAME(o.schema_id) [schema],o.name [object],i.name,i.type,i.is_unique,
              i.is_primary_key,i.is_unique_constraint,i.is_disabled,i.filter_definition,
              JSON_QUERY((SELECT COL_NAME(c.object_id,c.column_id) name,c.key_ordinal,c.is_descending_key,c.is_included_column
                FROM sys.index_columns c WHERE c.object_id=i.object_id AND c.index_id=i.index_id
                ORDER BY c.index_column_id FOR JSON PATH)) columns
              FROM sys.indexes i JOIN sys.objects o ON o.object_id=i.object_id
              WHERE o.is_ms_shipped=0 AND i.index_id>0 ORDER BY SCHEMA_NAME(o.schema_id),o.name,i.name FOR JSON PATH,INCLUDE_NULL_VALUES)) indexes,
            JSON_QUERY((SELECT SCHEMA_NAME(o.schema_id) [schema],o.name [object],c.name,c.definition,c.is_disabled,c.is_not_trusted
              FROM sys.check_constraints c JOIN sys.objects o ON o.object_id=c.parent_object_id
              ORDER BY SCHEMA_NAME(o.schema_id),o.name,c.name FOR JSON PATH,INCLUDE_NULL_VALUES)) checks,
            JSON_QUERY((SELECT SCHEMA_NAME(o.schema_id) [schema],o.name [object],f.name,
              OBJECT_SCHEMA_NAME(f.referenced_object_id) referenced_schema,OBJECT_NAME(f.referenced_object_id) referenced_table,
              f.delete_referential_action,f.update_referential_action,f.is_disabled,f.is_not_trusted,
              JSON_QUERY((SELECT COL_NAME(c.parent_object_id,c.parent_column_id) parent_column,
                COL_NAME(c.referenced_object_id,c.referenced_column_id) referenced_column
                FROM sys.foreign_key_columns c WHERE c.constraint_object_id=f.object_id ORDER BY c.constraint_column_id FOR JSON PATH)) columns
              FROM sys.foreign_keys f JOIN sys.objects o ON o.object_id=f.parent_object_id
              ORDER BY SCHEMA_NAME(o.schema_id),o.name,f.name FOR JSON PATH,INCLUDE_NULL_VALUES)) foreign_keys,
            JSON_QUERY((SELECT * FROM dbo.SchemaHistory ORDER BY Version FOR JSON PATH,INCLUDE_NULL_VALUES)) history
            FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES) SchemaInventory,
          CONVERT(int,@@SPID) Spid,@@TRANCOUNT TransactionCount,XACT_STATE() TransactionState,
          CONVERT(bit,CASE WHEN SESSION_CONTEXT(N'P7_RunId') IS NOT NULL OR SESSION_CONTEXT(N'P7_CompanyId') IS NOT NULL
            OR SESSION_CONTEXT(N'P7_FaultPoint') IS NOT NULL OR SESSION_CONTEXT(N'P7_CaseCode') IS NOT NULL THEN 1 ELSE 0 END) HasFaultMarkers
        FROM sys.databases d WHERE d.database_id=DB_ID();
        """;
}
